import AppKit
import CryptoKit
import ImageIO

enum ClipKind: String, Codable { case text, image, files }

/// One remembered copy. Small enough to keep in memory; anything heavy (rich text, images, very
/// long text) sits in a payload file next to the index and is read only when pasted or previewed.
struct ClipItem: Codable, Identifiable, Equatable {
  let id: UUID
  let kind: ClipKind
  /// What is shown and searched: the text itself (shortened if huge), file paths, or an image label.
  var text: String
  /// Same content, same hash: used to spot a repeated copy.
  let hash: String
  var date: Date
  var pinned = false
  /// The app it was copied from.
  var app: String?
  var hasPayload = false
  /// Characters for text, number of files, or pixel size for images.
  var detail: String?

  /// One tidy line for a list row.
  var title: String {
    switch kind {
    case .files:
      let names = text.split(separator: "\n").map { ($0 as NSString).lastPathComponent }
      return names.count > 3
        ? names.prefix(3).joined(separator: ", ") + " +\(names.count - 3)" : names.joined(separator: ", ")
    case .image: return text
    case .text:
      return text.prefix(300).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }
  }

  var symbol: String {
    switch kind {
    case .text: return text.hasPrefix("http://") || text.hasPrefix("https://") ? "link" : "text.alignleft"
    case .image: return "photo"
    case .files: return "doc"
    }
  }
}

/// What was just read off the pasteboard, before it becomes an item.
struct ClipCapture {
  let kind: ClipKind
  /// The full text (or file paths, one per line; or an image label).
  let text: String
  /// Pasteboard type -> data. Empty for short plain text and for files.
  let payload: [String: Data]
  let detail: String?

  var hash: String {
    var h = SHA256()
    h.update(data: Data(kind.rawValue.utf8))
    if kind == .image, let d = payload.values.first { h.update(data: d) } else { h.update(data: Data(text.utf8)) }
    return h.finalize().map { String(format: "%02x", $0) }.joined()
  }
}

/// Reading from and writing to a pasteboard.
enum ClipPasteboard {
  /// Markers apps (password managers, Kitbag's own dictation) put on copies that must not be kept.
  static let skipTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
  ]
  /// Text longer than this is kept in a payload file; the index keeps only the beginning.
  static let indexedTextLimit = 20_000
  static let maxBytes = 30 * 1024 * 1024
  static let plain = NSPasteboard.PasteboardType.string.rawValue

  static func read(_ pb: NSPasteboard) -> ClipCapture? {
    let types = pb.types ?? []
    guard !types.isEmpty, !types.contains(where: { skipTypes.contains($0.rawValue) }) else { return nil }

    if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
      as? [URL], !urls.isEmpty
    {
      return ClipCapture(
        kind: .files, text: urls.map(\.path).joined(separator: "\n"), payload: [:],
        detail: urls.count == 1 ? "1 file" : "\(urls.count) files")
    }

    if let s = pb.string(forType: .string),
      !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    {
      guard s.utf8.count <= maxBytes else { return nil }
      var payload: [String: Data] = [:]
      var size = 0
      for t in [NSPasteboard.PasteboardType.rtf, .html] {
        if let d = pb.data(forType: t), size + d.count <= maxBytes / 3 {
          payload[t.rawValue] = d
          size += d.count
        }
      }
      if !payload.isEmpty || s.utf16.count > indexedTextLimit { payload[plain] = Data(s.utf8) }
      return ClipCapture(kind: .text, text: s, payload: payload, detail: "\(s.count) characters")
    }

    for t in [NSPasteboard.PasteboardType.png, .tiff] {
      guard let d = pb.data(forType: t), d.count <= maxBytes else { continue }
      var label = "Image"
      var detail: String?
      if let src = CGImageSourceCreateWithData(d as CFData, nil),
        let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
        let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int
      {
        label = "Image \(w) × \(h)"
        detail = ByteCountFormatter.string(fromByteCount: Int64(d.count), countStyle: .file)
      }
      return ClipCapture(kind: .image, text: label, payload: [t.rawValue: d], detail: detail)
    }
    return nil
  }

  /// Puts the item back on the pasteboard. `plainText` drops fonts and colors (and turns files into paths).
  static func write(_ item: ClipItem, payload: [String: Data]?, plainText: Bool, to pb: NSPasteboard) {
    pb.clearContents()
    let fullText = payload?[plain].map { String(decoding: $0, as: UTF8.self) } ?? item.text
    switch item.kind {
    case .files where !plainText:
      pb.writeObjects(item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL })
    case .image:
      let entry = NSPasteboardItem()
      for (type, data) in payload ?? [:] { entry.setData(data, forType: .init(type)) }
      pb.writeObjects([entry])
    case .text where !plainText && payload != nil:
      let entry = NSPasteboardItem()
      for (type, data) in payload ?? [:] where type != plain { entry.setData(data, forType: .init(type)) }
      entry.setString(fullText, forType: .string)
      pb.writeObjects([entry])
    default:
      pb.setString(fullText, forType: .string)
    }
  }
}
